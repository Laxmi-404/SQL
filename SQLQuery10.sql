Where Salary=HighestSalary

--CALCULATE THE DEVIATION OF EACH SALE FROM BOTH THE MINIMUM AND MAXIMUM SALE AMOUNTS
SELECT *
FROM(
SELECT 
	OrderID,
	OrderDate,
	ProductID,
	Sales,
	MAX(Sales) OVER () HighestSales,
	MIN(Sales) OVER () LowestSales,
	Sales-MIN(Sales) OVER() DEVIATION_FROM_MIN,
	Max(Sales) Over()-Sales DEVIATION_FROM_MAX
	FROM Sales.Orders
)t

--CALCULATE THE MOVING AVERAGE OF SALES FOR EACH PRODUCT OVER TIME
SELECT
	OrderID,
	OrderDate,
	ProductID,
	Sales,
	AVG(Sales) OVER(PARTITION BY ProductID) AvgByProduct,
	AVG(Sales) OVER(PARTITION BY ProductID ORDER BY OrderDate) MOVINGAVG

FROM Sales.Orders

--CALCULATE THE MOVING AVERAGE OF SALES FOR EACH PRODUCT OVER TIME including only the next order
SELECT
	OrderID,
	OrderDate,
	ProductID,
	Sales,
	AVG(Sales) OVER(PARTITION BY ProductID) AvgByProduct,
	AVG(Sales) OVER(PARTITION BY ProductID ORDER BY OrderDate) MOVINGAVG,
	AVG(Sales) OVER(PARTITION BY ProductID Order BY OrderDate ROWS BETWEEN CURRENT ROW AND 1 FOLLOWING) RollingAvg
FROM Sales.Orders

