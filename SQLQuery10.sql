--MIN/MAX
--FIND THE highest and lowest SALES ACROSS ALL ORDERS AND highest and lowest  SALES FOR EACH PRODUCT.
--Additionally give OrderID AND ORDERDATE
SELECT
	OrderID,
	OrderDate,
	ProductID,
	Sales,
	MAX(Sales) OVER() HighestSales,
	MIN(Sales) OVER() LowestSales,
	MAX(Sales) OVER(PARTITION BY ProductID) HighestSalesByProduct,
	MIN(Sales) OVER(PARTITION BY ProductID) LowestSalesByProduct
FROM Sales.Orders

--SHOW THE EMPLOYEES WITH THE HIGHEST SALARIES
SELECT *
